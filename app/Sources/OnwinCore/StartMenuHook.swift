import Foundation

/// The `wineshelllink` hook that winemenubuilder calls for Start Menu / Desktop shortcuts.
///
/// The CW Wine tree builds winemenubuilder in CrossOver mode (`cx_mode = 1`,
/// `programs/winemenubuilder/cxmenu.c`). In that mode it writes no XDG `.desktop` files: for every
/// shortcut a program saves into the Start Menu or onto the Desktop (shell32 `IPersistFile::Save`
/// → `winemenubuilder -w <lnk>`, also msi `CreateShortcuts`) it extracts the icon into
/// `<prefix>/windata/cxmenu/icons/hicolor/<W>x<H>/apps/<name>.png` and runs, through the Unix PATH,
///
///     wineshelllink --utf8 --root <folder> --link <lnk> --path <target> --menu|--desktop
///                   [--args <arguments>] [--icon <name>] [--descr <description>]
///
/// Without such a script every shortcut logs `wineshelllink returned …`. onwin installs its own
/// script into `<onwin root>/Tools/bin` and puts that directory first on Wine's PATH
/// (`WineRunner.environment`), so it works with every engine, including ones built before the
/// script existed. The script only appends one JSON line per shortcut to
/// `<prefix>/onwin-menu.jsonl`; `LauncherBuilder.sync` turns those (and the Start Menu `.lnk`
/// files `ProgramScanner` finds) into `.app` launchers. It never fails: winemenubuilder treats a
/// non-zero exit as an error.
///
/// `winemenubuilder --cx-all-menus` (see `rescan`) re-runs the hook for every existing shortcut,
/// which also refreshes the extracted icons.
public enum StartMenuHook {
    /// Bump when the script text changes; the installed copy is rewritten when it differs.
    static let scriptVersion = 1

    /// Name of the file in the space that collects the shortcut records.
    public static let recordsFileName = "onwin-menu.jsonl"

    /// Directory put on Wine's PATH (`<onwin root>/Tools/bin`).
    public static var binDirectory: URL {
        OnwinPaths.root.appendingPathComponent("Tools/bin", isDirectory: true)
    }

    public static var scriptURL: URL { binDirectory.appendingPathComponent("wineshelllink") }

    /// Installs (or refreshes) the script and returns its directory, or nil when it cannot be
    /// written. Cheap after the first call in a process.
    @discardableResult
    public static func installIfNeeded() -> URL? {
        installState.withLock { state -> URL? in
            let ok = state ?? writeScript()
            state = ok
            return ok ? binDirectory : nil
        }
    }

    private static let installState = LockedValue<Bool?>(nil)

    private static func writeScript() -> Bool {
        let fm = FileManager.default
        let url = scriptURL
        let wanted = Data(script.utf8)
        if let current = fm.contents(atPath: url.path), current == wanted,
           fm.isExecutableFile(atPath: url.path) { return true }
        do {
            try fm.createDirectory(at: binDirectory, withIntermediateDirectories: true)
            try wanted.write(to: url, options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: url.path)
            return true
        } catch {
            return false
        }
    }

    /// The script. POSIX sh plus /usr/bin tools only: no python (on a Mac without Command Line
    /// Tools `python3` is a stub that pops up the CLT installer).
    public static let script = #"""
    #!/bin/sh
    # wineshelllink for onwin (generated by onwin, version \#(scriptVersion); do not edit — it is rewritten).
    # Called by CW winemenubuilder (cx_mode) for every Start Menu / Desktop shortcut, see
    # programs/winemenubuilder/cxmenu.c. Records the shortcut for onwin; onwin makes the .app launchers.
    prefix="${WINEPREFIX:-$HOME/.wine}"
    link=""; root=""; target=""; args=""; icon=""; descr=""; kind="menu"
    while [ $# -gt 0 ]; do
        case "$1" in
            --root)  root="${2-}";   [ $# -gt 1 ] && shift ;;
            --link)  link="${2-}";   [ $# -gt 1 ] && shift ;;
            --path)  target="${2-}"; [ $# -gt 1 ] && shift ;;
            --args)  args="${2-}";   [ $# -gt 1 ] && shift ;;
            --icon)  icon="${2-}";   [ $# -gt 1 ] && shift ;;
            --descr) descr="${2-}";  [ $# -gt 1 ] && shift ;;
            --desktop) kind="desktop" ;;
            --menu)    kind="menu" ;;
            *) ;;
        esac
        shift
    done
    [ -n "$link" ] || exit 0
    [ -d "$prefix" ] || exit 0
    esc() {
        printf '%s' "$1" | LC_ALL=C /usr/bin/sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' | LC_ALL=C /usr/bin/tr -d '\000-\037'
    }
    now=$(/bin/date +%s 2>/dev/null || echo 0)
    printf '{"v":1,"time":%s,"kind":"%s","link":"%s","root":"%s","path":"%s","args":"%s","icon":"%s","description":"%s"}\n' \
        "$now" "$kind" "$(esc "$link")" "$(esc "$root")" "$(esc "$target")" "$(esc "$args")" \
        "$(esc "$icon")" "$(esc "$descr")" >> "$prefix/\#(recordsFileName)" 2>/dev/null
    exit 0

    """#

    // MARK: Records

    /// One shortcut reported by winemenubuilder.
    public struct Entry: Codable, Hashable, Sendable {
        public var time: Double?
        /// "menu" or "desktop".
        public var kind: String?
        /// Windows path of the .lnk / .url file.
        public var link: String
        /// Start Menu / Desktop folder the link is in (Windows path).
        public var root: String?
        /// Windows path of the target, empty for URL shortcuts.
        public var path: String?
        public var args: String?
        /// Icon name under `windata/cxmenu/icons/hicolor/*/apps/`.
        public var icon: String?
        public var description: String?

        public var isDesktop: Bool { kind == "desktop" }
    }

    public static func recordsURL(in space: Space) -> URL {
        space.url.appendingPathComponent(recordsFileName)
    }

    /// Recorded shortcuts, latest record per link, keyed by the lowercased Unix path of the link.
    public static func entries(in space: Space) -> [String: Entry] {
        guard let data = try? Data(contentsOf: recordsURL(in: space)), !data.isEmpty else { return [:] }
        let decoder = JSONDecoder()
        var result: [String: Entry] = [:]
        for line in data.split(separator: UInt8(ascii: "\n")) where !line.isEmpty {
            guard let entry = try? decoder.decode(Entry.self, from: Data(line)),
                  let unix = space.unixPath(forWindowsPath: entry.link) else { continue }
            result[unix.standardizedFileURL.path.lowercased()] = entry
        }
        return result
    }

    /// The recorded entry for a Start Menu / Desktop .lnk file of the space.
    public static func entry(forLink link: URL, in space: Space, entries: [String: Entry]? = nil) -> Entry? {
        (entries ?? self.entries(in: space))[link.standardizedFileURL.path.lowercased()]
    }

    /// Largest PNG winemenubuilder extracted for an icon name, if any.
    public static func iconFile(named name: String, in space: Space) -> URL? {
        guard !name.isEmpty, !name.contains("/") else { return nil }
        let hicolor = space.url.appendingPathComponent("windata/cxmenu/icons/hicolor", isDirectory: true)
        let sizes = (try? FileManager.default.contentsOfDirectory(atPath: hicolor.path)) ?? []
        let ranked = sizes.compactMap { dir -> (Int, URL)? in
            let parts = dir.split(separator: "x")
            guard parts.count == 2, let w = Int(parts[0]), let h = Int(parts[1]) else { return nil }
            let file = hicolor.appendingPathComponent("\(dir)/apps/\(name).png")
            return OnwinPaths.exists(file) ? (w * h, file) : nil
        }
        return ranked.max { $0.0 < $1.0 }?.1
    }

    /// Runs `winemenubuilder --cx-all-menus`: the hook is called again for every shortcut in the
    /// Start Menu and on the Desktop, and icons are re-extracted. No windows are shown.
    public static func rescan(_ space: Space, engine: Engine? = nil) async throws {
        installIfNeeded()
        let runner = try WineRunner(space: space, engine: engine)
        _ = try await runner.runAndWait(["winemenubuilder.exe", "--cx-all-menus"])
    }
}

/// Tiny lock-protected box (Swift 5 mode, macOS 14: no `Synchronization.Mutex`).
final class LockedValue<Value>: @unchecked Sendable {
    private var value: Value
    private let lock = NSLock()

    init(_ value: Value) { self.value = value }

    func withLock<R>(_ body: (inout Value) -> R) -> R {
        lock.lock()
        defer { lock.unlock() }
        return body(&value)
    }
}
